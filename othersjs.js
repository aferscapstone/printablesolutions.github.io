const othersCategories = document.querySelectorAll(".others-category");

const productTitle = document.getElementById("productTitle");
const productDescription = document.getElementById("productDescription");
const productNote = document.getElementById("productNote");
const productTableBody = document.getElementById("productTableBody");
const productIcon = document.getElementById("productIcon");

othersCategories.forEach(category => {

    category.addEventListener("click", function () {

        // Remove active from all cards
        othersCategories.forEach(item => {
            item.classList.remove("active");
        });

        // Make clicked card active
        this.classList.add("active");

        // Get product name
        const productName = this.dataset.product;

        // Get product data
        const product = othersProducts[productName];

        // Change title
        productTitle.textContent = product.title;

        // Change description
        productDescription.innerHTML = product.description;

	productIcon.className = "";
	productIcon.classList.add("fa-solid");
	productIcon.classList.add(product.icon);

        // Clear old table
        productTableBody.innerHTML = "";

        // Create new table rows
        product.rows.forEach(row => {

            const tr = document.createElement("tr");

            tr.innerHTML = `
                <td>${row[0]}</td>
		<td>${row[1]}</td>
		<td>${row[2]}</td>
		<td>${row[3]}</td>
		<td>${row[4]}</td>
                <td>
                    <span class="stock">
                        <i class="fa-solid fa-circle-check"></i>
                        ${row[5]}
                    </span>
                </td>
            `;

            productTableBody.appendChild(tr);

        });

    });

});